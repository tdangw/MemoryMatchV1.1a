import assert from "node:assert/strict";
import { createActivePlayClock } from "../js/playMetrics.js";
let time = 100;
const clock = createActivePlayClock({ now: () => time });
time += 5000;
assert.equal(clock.durationMs(), 0, "Startup and preview must not count.");
clock.resume("startup");
time += 1000;
clock.pause("modal");
time += 9000;
clock.pause("hidden");
clock.resume("modal");
time += 5000;
assert.equal(clock.durationMs(), 1000, "Nested pause reasons cannot resume prematurely.");
clock.resume("hidden");
time += 1200;
assert.equal(clock.finish(), 2200);
time += 1000;
clock.resume("finished");
assert.equal(clock.durationMs(), 2200, "Finished clocks must never restart.");
const restored = createActivePlayClock({ now: () => time, elapsedMs: 2200 });
time += 100000;
assert.equal(restored.durationMs(), 2200, "Closed-app time must not count.");
restored.resume("startup");
time += 500;
assert.equal(restored.finish(), 2700);
console.log("Active play timing, nested modal/visibility pause, finalization and restoration checks passed.");
