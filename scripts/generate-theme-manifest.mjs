import { readdirSync, writeFileSync } from "node:fs";
import { relative, resolve } from "node:path";

const themesDirectory = resolve("public/assets/images/themes");
const outputFile = resolve("js/generated/themeAssetManifest.js");

const manifest = Object.fromEntries(
  readdirSync(themesDirectory, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .sort((left, right) => left.name.localeCompare(right.name, "en"))
    .map((directory) => {
      const files = collectThemeFiles(resolve(themesDirectory, directory.name))
        .sort((left, right) => left.path.localeCompare(right.path, "en"));

      return [directory.name, Object.freeze(files)];
    }),
);

const contents = `// Generated by scripts/generate-theme-manifest.mjs. Do not edit manually.\nexport const THEME_ASSET_MANIFEST = Object.freeze(${JSON.stringify(manifest, null, 2)});\n`;

writeFileSync(outputFile, contents, "utf8");
console.log(`Indexed ${Object.values(manifest).flat().length} theme images across ${Object.keys(manifest).length} folders.`);

function collectThemeFiles(directory, rootDirectory = directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const entryPath = resolve(directory, entry.name);
    if (entry.isDirectory()) return collectThemeFiles(entryPath, rootDirectory);
    if (!entry.isFile() || !entry.name.toLowerCase().endsWith(".webp")) return [];
    const path = relative(rootDirectory, entryPath).replaceAll("\\", "/");
    return [{ path, special: path.split("/").includes("special") }];
  });
}
