import assert from 'node:assert/strict';
import { setRankingOwner } from '../js/rankingOwner.js';
import { validateRankingResult, rankingBoardId, collectRankingResults } from '../js/rankingResult.js';
import { gameState, recordMemoryMatchResult, hydrateGameState } from '../js/gameState.js';
import { createRankedRun, finalizeRankedRun } from '../js/rankingRules.js';
setRankingOwner({ id: 'fixture-profile', uid: 'guest-a' });
recordMemoryMatchResult({ mode: 'easy', level: 1, score: 500, stars: 3, durationMs: 2000 });
recordMemoryMatchResult({ mode: 'easy', level: 1, score: 100, stars: 1, durationMs: 1000 });
const best = gameState.progress.memoryMatch.bestByLevel['easy:1'];
assert.equal(best.score, 500);
assert.equal(best.durationMs, 1000);
assert.equal(best.rankingResult.score, 100, 'Public result belongs to the fastest actual attempt, not aggregate maximum score.');
assert.equal(best.rankingResult.stars, 1);
assert(validateRankingResult(best.rankingResult));
assert.equal(rankingBoardId(best.rankingResult), 'v1_memory-match_easy_1');
assert.throws(() => rankingBoardId({ gameId: 'memory-match', mode: 'endless', kind: 'run' }));
assert.equal(validateRankingResult({ ...best.rankingResult, durationMs: 0 }), false);
const resultId = best.rankingResult.id;
hydrateGameState(structuredClone({ coins: 0, progress: gameState.progress, settings: {}, appearance: {} }));
assert.equal(gameState.progress.memoryMatch.bestByLevel['easy:1'].rankingResult.id, resultId);
const results = collectRankingResults({ profile: { data: { progress: {} } }, chapters: [{ key: 'memoryMatch:1', value: { bestByLevel: { 'easy:1': best } } }] });
assert.equal(results.length, 1);
gameState.progress.tripleConnect.runBests.challenge = { levelReached: 20, totalScore: 1000 };
gameState.progress.tripleConnect.activeRankedRuns.challenge = createRankedRun('triple-connect', 'challenge', 10, { rankable: true });
setRankingOwner({ id: 'other-profile', uid: 'google-b' });
const firstRun = finalizeRankedRun('triple-connect', 'challenge', 100);
assert.equal(firstRun.owner.uid, 'guest-a', 'A run keeps its start owner even if Auth changes while playing.');
assert.equal(gameState.progress.tripleConnect.runBests.challenge.levelReached, 20, 'Legacy aggregate best is preserved.');
assert.equal(gameState.progress.tripleConnect.runBests.challenge.rankingResult.levelReached, 10, 'A valid new run can publish despite a higher unowned legacy record.');
gameState.progress.tripleConnect.activeRankedRuns.challenge = createRankedRun('triple-connect', 'challenge', 2, { rankable: true });
finalizeRankedRun('triple-connect', 'challenge', 50);
assert.equal(gameState.progress.tripleConnect.runBests.challenge.rankingResult.owner.uid, 'google-b');
assert.equal(gameState.progress.tripleConnect.runBests.challenge.rankingResult.levelReached, 2);
assert.equal(gameState.progress.tripleConnect.runBests.challenge.levelReached, 20);
console.log('Leaderboard immutable attempt, reload/archive preservation and supported board validation passed.');
