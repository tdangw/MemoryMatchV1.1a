import fs from 'node:fs/promises';
import crypto from 'node:crypto';
import { COSMETIC_ITEMS } from '../js/progression/cosmeticCatalog.js';

const manifestPath='design/expedition/art-production/manifest.json';
const output='js/progression/cosmeticForms.generated.js';
const manifest=JSON.parse(await fs.readFile(manifestPath,'utf8'));
if(manifest.version!==1||!Array.isArray(manifest.records))throw new Error('Unsupported cosmetic art manifest');
const ids=new Set(COSMETIC_ITEMS.map(item=>item.id)), forms={}, seen=new Set();
const legacyPromptIds=new Set(['event-avatar-lantern-otter','starter-frame-plain-wood','starter-badge-first-leaf']);
const box=(value,width,height)=>Array.isArray(value)&&value.length===4&&value.every(Number.isFinite)
  &&value[0]>=0&&value[1]>=0&&value[2]>value[0]&&value[3]>value[1]&&value[2]<=width&&value[3]<=height;
function webpSize(bytes){
  const kind=bytes.toString('ascii',12,16);
  if(kind==='VP8X')return [bytes.readUIntLE(24,3)+1,bytes.readUIntLE(27,3)+1];
  if(kind==='VP8L'){const bits=bytes.readUInt32LE(21);return [(bits&16383)+1,((bits>>>14)&16383)+1];}
  if(kind==='VP8 ')return [bytes.readUInt16LE(26)&16383,bytes.readUInt16LE(28)&16383];
  throw new Error('Unsupported WebP header');
}
for(const record of manifest.records){
  if(!ids.has(record.id)||![2,3].includes(record.form))throw new Error('Unknown cosmetic form');
  const key=`${record.id}:${record.form}`;
  if(seen.has(key))throw new Error(`Duplicate form: ${key}`);seen.add(key);
  if(record.status!=='ready')continue;
  if(record.qa?.status!=='passed'||!record.alignment||record.canvas?.join(',')!=='512,512'
    ||!record.promptReference && !(legacyPromptIds.has(record.id)&&record.promptStatus==='original-verbatim-not-archived; use PROMPT_GUIDE.md for new edits')
    ||!Array.isArray(record.exports)||record.exports.length!==3)throw new Error(`Incomplete art handoff: ${key}`);
  if(typeof record.master!=='string'||!record.master.startsWith('design/expedition/art-production/masters/')||record.master.includes('..'))throw new Error(`Invalid master path: ${key}`);
  const master=await fs.readFile(record.master);
  if(crypto.createHash('sha256').update(master).digest('hex')!==record.masterSha256)throw new Error(`Master integrity failed: ${key}`);
  if(master.length<24||master.subarray(0,8).toString('hex')!=='89504e470d0a1a0a')throw new Error(`Invalid PNG master: ${key}`);
  const alignment=record.alignment,item=COSMETIC_ITEMS.find(item=>item.id===record.id);
  if(alignment.method!=='uniform-scale-and-translate'||!Number.isFinite(alignment.scale)||alignment.scale<=0
    ||!Array.isArray(alignment.translation)||alignment.translation.length!==2||!alignment.translation.every(Number.isFinite)
    ||!box(alignment.sourceAnchorBox,master.readUInt32BE(16),master.readUInt32BE(20))||!box(alignment.targetAnchorBox,512,512)
    ||alignment.anchorKind!==(item.type==='frame'?'inner-opening':'alpha-footprint'))throw new Error(`Invalid alignment contract: ${key}`);
  const files={};
  for(const size of [128,256,512]){
    const path=`assets/achievements/evolution/v1/${record.id}-form${record.form}-${size}.webp`;
    const file=record.exports.find(file=>file.path===path);
    if(!file||file.dimensions?.join(',')!==`${size},${size}`)throw new Error(`Missing export: ${path}`);
    const bytes=await fs.readFile(`public/${path}`);
    if(bytes.toString('ascii',0,4)!=='RIFF'||bytes.toString('ascii',8,12)!=='WEBP'||webpSize(bytes).join(',')!==`${size},${size}`
      ||bytes.length!==file.bytes||crypto.createHash('sha256').update(bytes).digest('hex')!==file.sha256)throw new Error(`Export integrity failed: ${path}`);
    files[size]=path;
  }
  (forms[record.id]||={})[record.form]=files;
}
const sorted=Object.fromEntries(Object.entries(forms).sort(([a],[b])=>a.localeCompare(b)));
const source=`// Generated by scripts/generate-cosmetic-forms.mjs. Ready, QA-passed forms only.\nexport const COSMETIC_FORMS = ${JSON.stringify(sorted,null,2)};\n`;
if(process.argv.includes('--check')){
  if(await fs.readFile(output,'utf8')!==source)throw new Error('Cosmetic forms catalog needs regeneration');
}else await fs.writeFile(output,source);
console.log(`Verified ${Object.values(forms).reduce((count,forms)=>count+Object.keys(forms).length,0)}/202 ready cosmetic forms.`);
