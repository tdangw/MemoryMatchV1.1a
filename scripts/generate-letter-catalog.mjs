import { createHash } from 'node:crypto';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const root='design/rewards-letters';
const source=JSON.parse(await fs.readFile(`${root}/catalog.source.json`,'utf8'));
assert(source.approvedForImplementation&&source.sharedPool);
assert.equal(source.items.length,12);assert.equal(new Set(source.items.map(item=>item.id)).size,12);
const manifest=process.argv.includes('--metadata-only')?null:JSON.parse(await fs.readFile(`${root}/art-manifest.json`,'utf8'));
if(manifest){const validation=JSON.parse(await fs.readFile(`${root}/review/alpha-validation.json`,'utf8'));assert(validation.fullExpansionComplete&&validation.checkedPairs===1521);}
const items=[];
for(const item of source.items){
  assert(['avatar','frame','badge'].includes(item.type));
  const files={};for(const size of [128,256,512]){
    const name=`${item.id}-${size}.webp`;
    if(manifest){const value=manifest.items[item.id];assert(value&&!value.nativeUpscaled&&value.type===item.type);const bytes=await fs.readFile(`${root}/${value.exports[size].file}`);assert.equal(createHash('sha256').update(bytes).digest('hex'),value.exports[size].sha256);await fs.writeFile(`public/assets/achievements/v1/${name}`,bytes);}
    files[size]=`assets/achievements/v1/${name}`;
  }
  items.push({id:item.id,name:item.name,type:item.type,sourceKind:'letters',series:'Sưu tập chữ',theme:item.theme,files});
}
await fs.writeFile('js/liveops/letterCatalog.generated.js','// Generated by scripts/generate-letter-catalog.mjs.\nexport const LETTER_REWARD_ITEMS = Object.freeze('+JSON.stringify(items,null,2)+'.map(Object.freeze));\n');
console.log('Generated12exclusive letter rewards; full mode validates and copies artwork.');
