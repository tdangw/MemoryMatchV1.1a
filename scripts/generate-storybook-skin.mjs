import fs from 'node:fs/promises';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import { UI_SKIN_ASSETS } from '../js/uiSkinManifest.js';
const source = 'design/storybook/packed', dest = 'public/assets/ui/storybook';
const manifest = JSON.parse(await fs.readFile(`${source}/manifest.json`, 'utf8'));
assert.equal(manifest.goldenApproved, true, 'Do not ship unapproved artwork');
await fs.mkdir(dest, { recursive: true });
const pack = { id: 'storybook', name: 'Cổ tích', base: 'assets/ui/storybook/',
  assets: {}, bundles: { core: [], rewards: [] }, nativeTreasure: false };
for (const [id, asset] of Object.entries(manifest.assets)) {
  const bytes = await fs.readFile(`${source}/${asset.file}`);
  assert.equal(crypto.createHash('sha256').update(bytes).digest('hex'), asset.sha256);
  await fs.writeFile(`${dest}/${asset.file}`, bytes);
  pack.assets[id] = asset; pack.bundles.core.push(id);
}
for (const tier of ['C', 'B', 'A', 'S']) for (const state of ['closed', 'open']) {
  const asset = UI_SKIN_ASSETS.assets[`chest-${tier}-${state}`];
  const file = `chest-${tier.toLowerCase()}-${state}.webp`;
  const bytes = await fs.readFile(`public/assets/ui/woodland/${asset.file}`);
  await fs.writeFile(`${dest}/${file}`, bytes);
  const id = `chest-${tier.toLowerCase()}-${state}`;
  pack.assets[id] = { file, width: asset.width, height: asset.height, bytes: bytes.length };
  pack.bundles.rewards.push(id);
}
for (const font of manifest.fonts) await fs.copyFile(`${source}/${font.file}`, `${dest}/${font.file}`);
await fs.copyFile(`${source}/OFL.txt`, `${dest}/OFL.txt`);
const fontCSS = (await fs.readFile(`${source}/font.css`, 'utf8')).replaceAll("url('./", "url('/assets/ui/storybook/");
await fs.writeFile(`${dest}/font.css`, fontCSS);
await fs.copyFile(`${source}/geometry.css`, `${dest}/geometry.css`);
await fs.writeFile('js/storybook/skin.generated.js', '// Generated by scripts/generate-storybook-skin.mjs.\nexport const STORYBOOK_UI_PACK = ' + JSON.stringify(pack, null, 2) + ';\n');
console.log('Prepared approved storybook skin: bounded core + lazy treasure bundle.');
