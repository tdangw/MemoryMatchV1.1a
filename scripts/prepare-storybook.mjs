import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { STORYBOOK_CONTRACT as contract } from '../design/storybook/contract.mjs';
const require = createRequire(import.meta.url);
const sharp = require(process.env.UI_SKIN_SHARP_MODULE || 'sharp');
const root = path.resolve(import.meta.dirname, '../design/storybook');
const output = path.join(root, 'packed');
await fs.mkdir(output, { recursive: true });
const sha = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const manifest = { version: 1, reviewOnly: !contract.review.goldenApproved, goldenApproved: contract.review.goldenApproved, assets: {}, fonts: [], budgets: contract.budgets };
for (const name of ['panel', 'ribbon', 'green', 'orange', 'leaves']) {
  const source = await fs.readFile(path.join(root, 'masters', `${name}.png`));
  const { data, info } = await sharp(source).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  let left = info.width, top = info.height, right = -1, bottom = -1;
  for (let y = 0; y < info.height; y++) for (let x = 0; x < info.width; x++) {
    if (data[(y * info.width + x) * 4 + 3] > 8) {
      left = Math.min(left, x); top = Math.min(top, y); right = Math.max(right, x); bottom = Math.max(bottom, y);
    }
  }
  assert(right > left && bottom > top, `Empty asset ${name}`);
  assert(left > 1 && top > 1 && right < info.width - 2 && bottom < info.height - 2, `Clipped source ${name}`);
  const bounds = { left, top, width: right - left + 1, height: bottom - top + 1 };
  const width = Math.min(bounds.width, name === 'panel' ? 760 : name === 'leaves' ? 192 : 960);
  const { data: bytes, info: packed } = await sharp(source).extract(bounds).resize({ width }).webp({ quality: 86, alphaQuality: 100 }).toBuffer({ resolveWithObject: true });
  await fs.writeFile(path.join(output, `${name}.webp`), bytes);
  const ratio = name === 'panel' ? .15 : name === 'ribbon' ? .24 : .18;
  manifest.assets[name] = { file: `${name}.webp`, width: packed.width, height: packed.height, bytes: bytes.length,
    sha256: sha(bytes), sourceSha256: sha(source), sourceSize: [info.width, info.height], sourceBounds: bounds,
    frame: [packed.width, packed.height], pivot: [.5, .5],
    cap: name === 'leaves' ? null : { x: Math.round(packed.width * ratio), y: name === 'panel' ? Math.round(packed.height * ratio) : 0 },
    renderMode: name === 'leaves' ? 'fixed-frame' : name === 'panel' ? 'nine-slice' : 'three-slice' };
}
const upstream = await fs.readFile(path.join(root, 'fonts/upstream.css'), 'utf8');
const fontCSS = [];
for (const subset of contract.font.subsets) {
  const block = upstream.match(new RegExp(`/\\* ${subset} \\*/\\s*(@font-face \\{[^}]+\\})`))[1];
  const bytes = await fs.readFile(path.join(root, 'fonts', `nunito-${subset}.woff2`));
  assert.equal(bytes.toString('ascii', 0, 4), 'wOF2');
  await fs.writeFile(path.join(output, `nunito-${subset}.woff2`), bytes);
  fontCSS.push(block.replace(/url\([^)]+\)/, `url('./nunito-${subset}.woff2')`).replace("'Nunito'", "'Storybook Nunito'"));
  manifest.fonts.push({ subset, file: `nunito-${subset}.woff2`, bytes: bytes.length, sha256: sha(bytes) });
}
await fs.copyFile(path.join(root, 'fonts/OFL.txt'), path.join(output, 'OFL.txt'));
await fs.writeFile(path.join(output, 'font.css'), '/* Generated by scripts/prepare-storybook.mjs. */\n' + fontCSS.join('\n'));
const variables = Object.entries(manifest.assets).filter(([, asset]) => asset.cap).map(([name, asset]) =>
  `  --storybook-${name}-slice: ${asset.cap.y} ${asset.cap.x};`);
await fs.writeFile(path.join(output, 'geometry.css'), '/* Generated by scripts/prepare-storybook.mjs. */\n.storybook-surface {\n' + variables.join('\n') + '\n}\n');
manifest.totalBytes = Object.values(manifest.assets).reduce((sum, a) => sum + a.bytes, 0) + manifest.fonts.reduce((sum, f) => sum + f.bytes, 0);
manifest.decodedBytes = Object.values(manifest.assets).reduce((sum, a) => sum + a.width * a.height * 4, 0);
assert(manifest.totalBytes <= contract.budgets.coreBytes, 'Core exceeds approved budget');
assert(manifest.decodedBytes < contract.budgets.liveDecodedBytes);
await fs.writeFile(path.join(output, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log(JSON.stringify({ result: 'PASS', assets: 5, fonts: 3, bytes: manifest.totalBytes, decodedBytes: manifest.decodedBytes }));
