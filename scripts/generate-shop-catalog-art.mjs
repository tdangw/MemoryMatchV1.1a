import {readFile,writeFile,unlink} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const root=new URL('../',import.meta.url);
const manifest=JSON.parse(await readFile(new URL('design/shop-catalog/art-manifest.json',root),'utf8'));
const inventory=JSON.parse(await readFile(new URL('design/shop-catalog/capture-manifest.json',root),'utf8'));
const expected=new Set([...inventory.entries.map(item=>`${item.kind}/${item.id}`),...['hint','time','preview','undo','shuffle','freeze','thunder','expand'].map(kind=>`support/${kind}`)]);
if(expected.size!==Object.keys(manifest.assets).length||[...expected].some(key=>!manifest.assets[key]))throw new Error('Catalog artwork coverage differs from its source inventory');
const mapping={};
for(const [key,asset] of Object.entries(manifest.assets)){
  for(const file of Object.values(asset.files)){
    const bytes=await readFile(new URL(`public${file.url}`,root));
    if(createHash('sha256').update(bytes).digest('hex')!==file.sha256)throw new Error(`Catalog art hash differs: ${key}`);
  }
  mapping[key]={small:asset.files['128'].url,large:asset.files['256'].url,...(asset.numberAnchor?{numberAnchor:asset.numberAnchor}:{})};
}
const source=`// Generated by scripts/generate-shop-catalog-art.mjs. Do not edit.\nexport const CATALOG_ART = Object.freeze(${JSON.stringify(mapping,null,2)});\n`;
const destination=new URL('js/generated/catalogArtManifest.js',root);
if(process.argv.includes('--check')){if(await readFile(destination,'utf8')!==source)throw new Error('Catalog art manifest needs regeneration');}
else {
  await writeFile(destination,source);
  // Retire only hash-verified exports created by this catalog task. Never walk
  // or delete any other asset namespace, source image, master or art journal.
  const previous=JSON.parse(await readFile(new URL('design/shop-catalog/previous-public-manifest.json',root),'utf8'));
  const current=new Set(Object.values(manifest.assets).flatMap(a=>Object.values(a.files).map(f=>f.url)));
  for(const asset of Object.values(previous.assets))for(const file of Object.values(asset.files)){
    if(current.has(file.url))continue;
    if(!/^\/assets\/shop-catalog\/v1\/[a-z0-9-]+\.webp$/.test(file.url))throw new Error('Retired art escaped its owner');
    const path=new URL(`public${file.url}`,root);let bytes;
    try{bytes=await readFile(path);}catch(error){if(error.code==='ENOENT')continue;throw error;}
    if(createHash('sha256').update(bytes).digest('hex')!==file.sha256)throw new Error('Retired art was changed by another owner');
    await unlink(path);
  }
}
console.log(`Catalog art: ${Object.keys(mapping).length} mappings verified`);
