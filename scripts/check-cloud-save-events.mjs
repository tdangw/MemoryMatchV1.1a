import assert from 'node:assert/strict';
import { createCloudSaveEventFilter, cloudSaveEventSignature } from '../js/cloudSaveEvents.js';
const progress = { memoryMatch: { bestByLevel: {}, items: { hint: 2 }, sessionsByMode: {} } };
const check = createCloudSaveEventFilter(progress);
progress.memoryMatch.sessionsByMode.easy = { level: 1, remainingTime: 50 };
assert.equal(check({ progress }), false, 'Session checkpoints are local only.');
progress.memoryMatch.sessionsByMode.easy.remainingTime = 49;
assert.equal(check({ progress }), false);
progress.memoryMatch.bestByLevel['easy:1'] = { cleared: true, stars: 0, score: 0 };
assert.equal(check({ progress, cloudEvent: true }), true, 'A zero-star win triggers backup.');
assert.equal(check({ progress }), false, 'The same completed result is not a new event.');
progress.memoryMatch.items.hint -= 1;
assert.equal(check({ progress }), true);
assert.equal(check({ coins: 123 }), true);
assert.equal(check({ coins: 123, progress }), false, 'Unchanged economy is not a save event.');
assert.equal(check({ appearance: { theme: 'garden' } }), true);
assert.equal(check({ settings: { musicVolume: .5 } }), false);
progress.memoryMatch.bestByLevel = { 'easy:101': { cleared: true, stars: 0, score: 0 } };
assert.equal(check({ progress }), false, 'Loading a different resident chapter is not a save event.');
progress.themeSelectionHistory = [{ theme: 'garden' }];
assert.equal(check({ progress }), false, 'Board selection history is a local checkpoint.');
assert.equal(cloudSaveEventSignature({ coins: 0, progress: {}, appearance: {} }), cloudSaveEventSignature({ coins: 0, progress: { memoryMatch: { adventure: { unlockedThrough: 1, completedCount: 0, lastLevel: 100, firstLevel: 1, currentChapter: 1 }, items: { hint: 0 }, totalStars: 0, totalScore: 0 } }, appearance: {} }), 'Cloud key ordering and normalized defaults do not create events.');
console.log('Cloud backup event boundaries passed.');
