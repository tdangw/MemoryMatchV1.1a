import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
const root = 'docs/design/achievements/art-kit-v1';
const assignments = JSON.parse(await fs.readFile(`${root}/reward-distribution.json`, 'utf8'));
const manifest = JSON.parse(await fs.readFile(`${root}/manifest.json`, 'utf8'));
const items = [], seen = new Set();
const dest = 'public/assets/achievements/v1'; await fs.mkdir(dest, { recursive: true });
for (const [gameId, ids] of Object.entries(assignments.games)) {
  assert.equal(ids.length, 10);
  for (const [index, id] of ids.entries()) {
    assert(!seen.has(id)); seen.add(id);
    const art = manifest.items[id]; assert.equal(art.game, gameId);
    const files = {};
    for (const size of [128, 256, 512]) {
      const source = size === 512 ? { file: art.file, sha256: art.sha256 } : art.exports[String(size)];
      const bytes = await fs.readFile(`${root}/${source.file}`);
      assert.equal(crypto.createHash('sha256').update(bytes).digest('hex'), source.sha256);
      const name = `${id}-${size}.webp`; await fs.writeFile(`${dest}/${name}`, bytes);
      files[size] = `assets/achievements/v1/${name}`;
    }
    items.push({ id, name: art.name, gameId, level: index + 1, type: art.type, equipSlot: art.equipSlot || art.type,
      achievementOnly: true, catalogVersion: assignments.catalogVersion, files });
  }
}
assert.equal(items.length, 30);
const legacyPublicIds = items.filter(item => item.type !== 'effect-cover').map(item => item.id);
const expansionRoot = 'design/rewards-liveops';
const expansion = JSON.parse(await fs.readFile(`${expansionRoot}/catalog.source.json`, 'utf8'));
const extras = JSON.parse(await fs.readFile(`${expansionRoot}/cosmetic-extras.source.json`, 'utf8'));
const art = JSON.parse(await fs.readFile(`${expansionRoot}/art-manifest.json`, 'utf8'));
const validation = JSON.parse(await fs.readFile(`${expansionRoot}/review/alpha-validation.json`, 'utf8'));
assert(expansion.approvedForImplementation && validation.fullExpansionComplete && validation.checkedPairs === 1225);
const extraItems = [];
for (const item of [...expansion.items, ...extras.items]) {
  assert(!seen.has(item.id)); seen.add(item.id);
  const source = art.items[item.id]; assert(source && !source.nativeUpscaled);
  const files = {};
  for (const size of [128, 256, 512]) {
    const output = source.exports[size], bytes = await fs.readFile(`${expansionRoot}/${output.file}`);
    assert.equal(crypto.createHash('sha256').update(bytes).digest('hex'), output.sha256);
    const name = `${item.id}-${size}.webp`; await fs.writeFile(`${dest}/${name}`, bytes);
    files[size] = `assets/achievements/v1/${name}`;
  }
  if (item.gameId) {
    assert(item.level >= 11 && item.level <= 30);
    items.push({ id: item.id, name: item.name, gameId: item.gameId, level: item.level, type: item.type,
      equipSlot: item.type, achievementOnly: true, catalogVersion: 1, files });
  } else extraItems.push({ id: item.id, name: item.name, type: item.type, sourceKind: item.sourceKind, series: item.series, files });
}
items.sort((a, b) => Object.keys(assignments.games).indexOf(a.gameId) - Object.keys(assignments.games).indexOf(b.gameId) || a.level - b.level);
assert.equal(items.length, 90); assert.equal(extraItems.length, 5);
assert.equal(new Set(items.map(item => `${item.gameId}:${item.level}`)).size, 90);
const output = '// Generated by scripts/generate-achievement-catalog.mjs.\n'
  + 'export const ACHIEVEMENT_ITEMS = Object.freeze(' + JSON.stringify(items, null, 2) + '.map(Object.freeze));\n'
  + 'export const EXTRA_COSMETIC_ITEMS = Object.freeze(' + JSON.stringify(extraItems, null, 2) + '.map(Object.freeze));\n';
await fs.writeFile('js/progression/achievementCatalog.generated.js', output
  + 'export const LEGACY_PUBLIC_COSMETIC_IDS = Object.freeze(' + JSON.stringify(legacyPublicIds) + ');\n');
console.log('Generated 90 stable game/level grants and five independent cosmetics; 285 lazy artwork files.');
