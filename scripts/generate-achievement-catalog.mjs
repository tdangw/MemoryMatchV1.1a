import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
const root = 'docs/design/achievements/art-kit-v1';
const assignments = JSON.parse(await fs.readFile(`${root}/reward-distribution.json`, 'utf8'));
const manifest = JSON.parse(await fs.readFile(`${root}/manifest.json`, 'utf8'));
const items = [], seen = new Set();
const dest = 'public/assets/achievements/v1'; await fs.mkdir(dest, { recursive: true });
for (const [gameId, ids] of Object.entries(assignments.games)) {
  assert.equal(ids.length, 10);
  for (const [index, id] of ids.entries()) {
    assert(!seen.has(id)); seen.add(id);
    const art = manifest.items[id]; assert.equal(art.game, gameId);
    const files = {};
    for (const size of [128, 256, 512]) {
      const source = size === 512 ? { file: art.file, sha256: art.sha256 } : art.exports[String(size)];
      const bytes = await fs.readFile(`${root}/${source.file}`);
      assert.equal(crypto.createHash('sha256').update(bytes).digest('hex'), source.sha256);
      const name = `${id}-${size}.webp`; await fs.writeFile(`${dest}/${name}`, bytes);
      files[size] = `assets/achievements/v1/${name}`;
    }
    items.push({ id, name: art.name, gameId, level: index + 1, type: art.type, equipSlot: art.equipSlot || art.type,
      achievementOnly: true, catalogVersion: assignments.catalogVersion, files });
  }
}
assert.equal(items.length, 30);
await fs.writeFile('js/progression/achievementCatalog.generated.js', '// Generated by scripts/generate-achievement-catalog.mjs.\nexport const ACHIEVEMENT_ITEMS = Object.freeze(' + JSON.stringify(items, null, 2) + '.map(Object.freeze));\n');
console.log('Generated 30 distinct game/level grants and 90 lazy artwork files.');
