"""Extract approved sheet regions and encode runtime art. Does not draw or repaint."""
from pathlib import Path
import hashlib
import json
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'docs/design/ui-images'
TARGET = ROOT / 'public/assets/images/ui/v1'
TARGET.mkdir(parents=True, exist_ok=True)
regions = json.loads((SOURCE / 'regions.json').read_text(encoding='utf-8'))
previous_path = SOURCE / 'runtime-metadata.json'
previous = json.loads(previous_path.read_text(encoding='utf-8'))['assets'] if previous_path.exists() else []
metadata, icons, tokens = [], {}, []
totals = {'garden': 0, 'reward': 0, 'icons': 0}
# Ignore nearly invisible alpha noise when finding content bounds, retaining
# the original alpha within the crop so painted edges remain antialiased.
ALPHA_CROP_THRESHOLD = 8
for entry in regions:
    with Image.open(SOURCE / 'masters' / entry['source']) as master:
        assert master.mode == 'RGBA', 'Transparent RGBA master required'
        rect = entry['rect']
        assert 0 <= rect[0] < rect[2] <= master.width and 0 <= rect[1] < rect[3] <= master.height
        piece = master.crop(rect)
        bounds = piece.getchannel('A').point(lambda alpha: 255 if alpha > ALPHA_CROP_THRESHOLD else 0).getbbox()
        assert bounds, f"Empty region: {entry['name']}"
        piece = piece.crop(bounds)
        source_size = piece.size
        piece.thumbnail((entry['maxSize'], entry['maxSize']), Image.Resampling.LANCZOS)
        destination = TARGET / f"{entry['name']}.webp"
        piece.save(destination, 'WEBP', quality=82, method=6, exact=True)
    url = '/' + destination.relative_to(ROOT / 'public').as_posix()
    tokens.append(f"  --ui-art-{entry['name']}: url('{url}');")
    for icon in entry['icons']:
        assert icon not in icons, f'Duplicate icon {icon}'
        icons[icon] = url
    size = destination.stat().st_size
    totals[entry['group']] += size
    metadata.append({**entry, 'sourceSize': source_size, 'size': piece.size, 'bytes': size,
                     'url': url, 'sha256': hashlib.sha256(destination.read_bytes()).hexdigest()})
assert totals['garden'] <= 350_000, totals
assert totals['reward'] <= 250_000, totals
assert totals['icons'] <= 250_000, totals
# Remove only exports owned by the previous manifest that the source catalog retired.
active_names = {entry['name'] for entry in regions}
for entry in previous:
    if entry['name'] in active_names:
        continue
    obsolete = (TARGET / f"{entry['name']}.webp").resolve()
    assert obsolete.parent == TARGET.resolve(), 'Export must stay inside the generated asset folder'
    obsolete.unlink(missing_ok=True)
(ROOT / 'styles/ui-art-tokens.css').write_text('/* Generated by prepare-ui-image-assets.py. */\n:root {\n' + '\n'.join(tokens) + '\n}\n', encoding='utf-8')
(ROOT / 'js/uiArtManifest.js').write_text('// Generated by prepare-ui-image-assets.py.\nexport const UI_ART_ICONS = Object.freeze(' + json.dumps(icons, ensure_ascii=False, indent=2) + ');\n', encoding='utf-8')
(SOURCE / 'runtime-metadata.json').write_text(json.dumps({'totals': totals, 'assets': metadata}, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
print(json.dumps({'assets': len(metadata), 'bytes': totals}))
