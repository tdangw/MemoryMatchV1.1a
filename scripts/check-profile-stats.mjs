import assert from 'node:assert/strict';
import { normalizeProfileStats, mergeProfileCounter, profileDisplayTotal, formatProfilePlaytime, adoptProfileStats } from '../js/profileStatsModel.js';
import 'fake-indexeddb/auto';
import { openChapterDatabase, updateChapterMetadataPair, writeChapterMetadata, readChapterMetadata } from '../js/chapterStore.js';
import { createActivePlayClock } from '../js/playMetrics.js';
const a = crypto.randomUUID(); const b = crypto.randomUUID();
let value = mergeProfileCounter(null, a, 60000, 1000);
value = mergeProfileCounter(value, b, 120000, 2000);
assert.equal(value.totalPlayMs, 180000);
assert.deepEqual(mergeProfileCounter(value, a, 60000, 1000), value, 'Replay is idempotent.');
value = mergeProfileCounter(value, a, 90000, 1000);
assert.equal(value.totalPlayMs, 210000);
assert.equal(mergeProfileCounter(value, a, 1, 1000).totalPlayMs, 210000, 'Stale device never lowers its counter.');
const local = { ...normalizeProfileStats(null, 2000), totalMs: 100000, acknowledgedMs: 90000, remoteTotalMs: 210000 };
assert.equal(profileDisplayTotal(local), 220000);
assert.equal(formatProfilePlaytime(3660000), '1 giờ 1 phút');
assert.throws(() => normalizeProfileStats({ ...local, acknowledgedMs: 100001 }));
assert.throws(() => normalizeProfileStats({ ...local, totalMs: -1 }));
assert.equal(normalizeProfileStats(null, 1).profileCreatedAt, null, 'Never invent an old account creation date.');
const full = { counters: Object.fromEntries(Array.from({ length: 128 }, () => [crypto.randomUUID(), 1])), totalPlayMs: 128, trackedSince: 1 };
assert.throws(() => mergeProfileCounter(full, crypto.randomUUID(), 1, 1), /capacity/);
assert.equal(mergeProfileCounter(full, Object.keys(full.counters)[0], 2, 1).totalPlayMs, 129);
const original = { ...normalizeProfileStats(null, 1), totalMs: 1000 };
const adopted = adoptProfileStats(original, null, 'first', 'local');
assert.equal(adopted[1].totalMs, 1000);
assert.deepEqual(adoptProfileStats(...adopted, 'first', 'local'), adopted, 'Adoption replay never doubles time.');
const race = adoptProfileStats(adopted[0], null, 'second', 'local');
assert.equal(race[0].adoptedUid, 'first'); assert.equal(race[1].totalMs, 0, 'Concurrent adopter cannot repoint the marker.');
const database = await openChapterDatabase();
await writeChapterMetadata(database, 'stats-local', original);
const put = IDBObjectStore.prototype.put;
IDBObjectStore.prototype.put = function(value, key) { if (key === 'stats-uid') throw new DOMException('Fixture quota', 'QuotaExceededError'); return put.call(this, value, key); };
await assert.rejects(updateChapterMetadataPair(database, ['stats-local', 'stats-uid'], values => adoptProfileStats(...values, 'first', 'local')), /quota/);
IDBObjectStore.prototype.put = put;
assert.deepEqual(await readChapterMetadata(database, 'stats-local'), original);
assert.equal(await readChapterMetadata(database, 'stats-uid'), undefined);
await updateChapterMetadataPair(database, ['stats-local', 'stats-uid'], values => adoptProfileStats(...values, 'first', 'local'));
assert.equal((await readChapterMetadata(database, 'stats-uid')).totalMs, 1000); database.close();
let now = 0; const segments = [];
const clock = createActivePlayClock({ now: () => now, onSegment: value => segments.push(value) });
clock.resume('startup'); now = 30000; clock.checkpoint(); now = 31000; clock.pause('menu');
now = 50000; clock.checkpoint(); clock.resume('menu'); now = 51000; clock.finish(); clock.finish(); clock.pause('cleanup');
assert.deepEqual(segments, [30000, 1000, 1000]); assert.equal(clock.durationMs(), 32000);
console.log('Private profile counters, replay/stale/multi-device totals, old-data validation and checkpoint ownership passed.');
