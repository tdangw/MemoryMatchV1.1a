import assert from 'node:assert/strict';
import { gameState, hydrateGameState, resetGame } from '../js/gameState.js';

hydrateGameState();
assert.equal(gameState.hints, 3);
gameState.hints = 9;
resetGame();
assert.equal(gameState.hints, 9, 'new game must retain inventory');
assert.equal(gameState.progress.memoryMatch.items.hint, 9);
hydrateGameState({ progress: { memoryMatch: { sessionsByMode: { easy: { mode: 'easy', hints: 7 }, hard: { mode: 'hard', hints: 12 } } } } });
assert.equal(gameState.hints, 12, 'migrate highest snapshot, do not sum duplicates');
assert.equal(gameState.progress.memoryMatch.sessionsByMode.easy.hints, undefined);
const migrated = structuredClone(gameState.progress);
hydrateGameState({ progress: migrated });
assert.equal(gameState.hints, 12, 'migration must not grant again');
migrated.memoryMatch.items.hint = 0;
migrated.memoryMatch.sessionsByMode.easy.hints = 90;
migrated.linkConnect.items.hint = 8;
hydrateGameState({ progress: migrated });
assert.equal(gameState.hints, 0, 'zero inventory wins over old session');
resetGame();
assert.equal(gameState.hints, 0);
assert.equal(gameState.progress.linkConnect.items.hint, 8, 'Memory reset cannot change Link inventory');
hydrateGameState({ progress: { memoryMatch: { activeSession: { mode: 'easy', hints: 0 } } } });
assert.equal(gameState.hints, 0, 'legacy empty inventory must not get starter grant again');
console.log('Hint inventory migration and reset checks passed.');
