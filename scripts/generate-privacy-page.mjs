import { writeFile } from 'node:fs/promises';
import { mkdir } from 'node:fs/promises';
import { PRIVACY_CONTENT } from '../js/privacyContent.js';
import { TERMS_CONTENT } from '../js/termsContent.js';
import { DELETION_CONTENT } from '../js/deletionContent.js';

await mkdir(new URL('../public/legal/', import.meta.url), { recursive: true });
for (const [file, title, content, relatedFile, relatedTitle] of [
  ['privacy', 'Quyền riêng tư', PRIVACY_CONTENT, 'terms', 'Điều khoản sử dụng'],
  ['terms', 'Điều khoản sử dụng', TERMS_CONTENT, 'privacy', 'Quyền riêng tư'],
  ['delete-account', 'Xóa tài khoản', DELETION_CONTENT, 'privacy', 'Quyền riêng tư'],
]) {
await writeFile(new URL(`../public/legal/${file}.html`, import.meta.url), `<!doctype html>
<!-- Generated by scripts/generate-privacy-page.mjs. -->
<html lang="vi"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>${title} · Memory Match Adventure</title>
<style>body{margin:0;background:#071f29;color:#f4eee0;font:17px/1.7 system-ui,sans-serif}main{max-width:760px;margin:auto;padding:32px max(24px,env(safe-area-inset-left)) max(32px,env(safe-area-inset-bottom))}h1{font-size:clamp(26px,6vw,36px);line-height:1.25}h3{font-size:21px;color:#f6d68b;margin-top:30px}a{color:#b8e6ef;overflow-wrap:anywhere}a:focus-visible{outline:2px solid #f6d68b;outline-offset:4px}</style></head>
<body><main><h1>${title}</h1>${content}<p><a href="${relatedFile}.html">${relatedTitle}</a></p>${file !== 'delete-account' ? '<p><a href="delete-account.html">Xóa tài khoản</a></p>' : ''}<p><a href="../../">Về trò chơi</a></p></main></body></html>\n`);
}
console.log('Generated public legal pages.');
