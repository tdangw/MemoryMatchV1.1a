import assert from "node:assert/strict";
import "fake-indexeddb/auto";
import { encodeCloudSnapshot, decodeCloudSnapshot, stableJSON } from "../js/cloudSnapshot.js";
import { openChapterDatabase, exportChapterSnapshot, replaceChapterSnapshot, readChapterMetadata, readChapterBackups, writeChapterProfile } from "../js/chapterStore.js";

const database = await openChapterDatabase();
const data = { coins: 100, progress: { memoryMatch: { bestByLevel: { "easy:1": { score: 10, stars: 0 } }, sessionsByMode: {} } }, appearance: {}, settings: { sound: false } };
await writeChapterProfile(database, { formatVersion: 2, revision: 1, updatedAt: 1, data }, 0);
const snapshot = await exportChapterSnapshot(database);
const encoded = await encodeCloudSnapshot(snapshot);
const decoded = await decodeCloudSnapshot(encoded.manifest, async hash => encoded.objects.get(hash));
assert.deepEqual(decoded.chapters, snapshot.chapters);
assert.deepEqual(decoded.profile.data, snapshot.profile.data);
const reordered = structuredClone(snapshot);
reordered.profile.revision += 10;
assert.equal((await encodeCloudSnapshot(reordered)).fingerprint, encoded.fingerprint, "Local revision metadata does not trigger cloud history rewrites.");
const oversizedSession = structuredClone(snapshot);
oversizedSession.profile.data.progress.memoryMatch.sessionsByMode.easy = { text: "đ🙂".repeat(40000) };
const large = await encodeCloudSnapshot(oversizedSession);
assert.ok(large.manifest.profile.length > 1);
assert.deepEqual((await decodeCloudSnapshot(large.manifest, async hash => large.objects.get(hash))).profile.data, oversizedSession.profile.data);
assert.deepEqual(large.manifest["chapter:memoryMatch:1"], encoded.manifest["chapter:memoryMatch:1"], "Unchanged historical chapters keep their hashes.");
await assert.rejects(decodeCloudSnapshot(encoded.manifest, async hash => ({ ...encoded.objects.get(hash), payload: "YmFk" })), /toàn vẹn|không hợp lệ/);
const cycle = {}; cycle.self = cycle;
assert.throws(() => stableJSON(cycle), /tham chiếu vòng/);
const changed = structuredClone(decoded);
changed.profile.data.coins = 500;
await replaceChapterSnapshot(database, changed, { ...changed.profile, revision: 2 }, 1, "cloud:local", { uid: "google", cloudRevision: 2 });
assert.equal((await exportChapterSnapshot(database)).profile.data.coins, 500);
assert.equal((await readChapterBackups(database))[0].profile.data.coins, 100);
assert.equal((await readChapterMetadata(database, "cloud:local")).uid, "google");
await assert.rejects(replaceChapterSnapshot(database, decoded, { ...decoded.profile, revision: 3 }, 1, "cloud:local", { uid: "other" }), /tab khác/);
assert.equal((await exportChapterSnapshot(database)).profile.data.coins, 500);
assert.equal((await readChapterMetadata(database, "cloud:local")).uid, "google");
const originalPut = IDBObjectStore.prototype.put;
IDBObjectStore.prototype.put = function (...args) { if (this.name === "profile") throw new DOMException("Import quota failure", "QuotaExceededError"); return originalPut.apply(this, args); };
await assert.rejects(replaceChapterSnapshot(database, decoded, { ...decoded.profile, revision: 3 }, 2, "cloud:local", { uid: "other" }), /quota/);
IDBObjectStore.prototype.put = originalPut;
assert.equal((await exportChapterSnapshot(database)).profile.data.coins, 500);
assert.equal((await readChapterMetadata(database, "cloud:local")).uid, "google");
assert.equal((await readChapterBackups(database)).length, 1);
for (let revision = 3; revision <= 6; revision += 1) await replaceChapterSnapshot(database, decoded, { ...decoded.profile, revision }, revision - 1, "cloud:local", { uid: "google" });
assert.equal((await readChapterBackups(database)).length, 3);
database.close();
console.log("Cloud chunk integrity/Unicode, incremental history, atomic identity/import rollback and bounded recovery backups passed.");
