import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
const root = path.resolve(import.meta.dirname, '..');
const source = path.join(root, 'docs/design/ui-style-expansion');
const contractBytes = await fs.readFile(path.join(source, 'asset-contract.json'));
const contract = JSON.parse(contractBytes);
const packs = {}, css = ['/* Generated by scripts/generate-ui-style-packs.mjs. Edit the source contract/manifest generator. */'];
for (const skin of ['papercut', 'starship']) {
  const dir = path.join(source, skin);
  const manifest = JSON.parse(await fs.readFile(path.join(dir, 'manifest.json'), 'utf8'));
  assert.equal(manifest.contractSha256, crypto.createHash('sha256').update(contractBytes).digest('hex'), 'Regenerate the source kit metadata after a contract change');
  assert.equal(Object.keys(manifest.assets).length, 52);
  assert.equal(Object.keys(manifest.vectors).length, 66);
  const assets = {}, bundles = { core: [], rewards: [] }, variables = [];
  async function copy(file, checksum) {
    assert(!file.includes('..') && /^(pieces|sprites|icons)\//.test(file), 'Only selected runtime assets may be copied');
    const bytes = await fs.readFile(path.join(dir, file));
    assert.equal(crypto.createHash('sha256').update(bytes).digest('hex'), checksum, skin + '/' + file);
    const dest = path.join(root, 'public/assets/ui', skin, file);
    await fs.mkdir(path.dirname(dest), { recursive: true });
    await fs.writeFile(dest, bytes);
    return bytes.length;
  }
  for (const [id, a] of Object.entries(manifest.assets)) {
    assert(['nine-slice', 'stretch-piece', 'fixed-frame'].includes(a.renderMode));
    const piece = a.renderMode !== 'fixed-frame';
    assert.equal(a.preferredFile, piece ? a.piece : a.file);
    const bytes = await copy(a.preferredFile, a.preferredSha256);
    assets[id] = { file: a.preferredFile, width: piece ? a.contentRect.width : a.frame.width,
      height: piece ? a.contentRect.height : a.frame.height, bytes, renderMode: a.renderMode,
      nineSlice: a.nineSlice, frame: a.frame, contentRect: a.contentRect, pivot: a.pivot,
      hotspot: a.hotspot || null, referenceBorderCss: a.referenceBorderCss, textInset: a.textInset };
    bundles[a.sheet === 'rewards' ? 'rewards' : 'core'].push(id);
    variables.push(`--skin-${id}: url('/assets/ui/${skin}/${a.preferredFile}');`);
    if (a.nineSlice) variables.push(`--skin-${id}-slice: ${['top','right','bottom','left'].map(k => a.nineSlice[k]).join(' ')};`);
  }
  for (const [name, vector] of Object.entries(manifest.vectors)) {
    const bytes = await copy(vector.file, vector.sha256);
    const id = 'vector-' + name;
    assets[id] = { file: vector.file, width: 24, height: 24, bytes, renderMode: 'vector' };
    bundles.core.push(id);
    css.push(`html[data-ui-skin="${skin}"] svg.ui-icon.ui-icon--${name} { background: url('/assets/ui/${skin}/${vector.file}') center / contain no-repeat; }`,
      `html[data-ui-skin="${skin}"] svg.ui-icon.ui-icon--${name} > * { visibility: hidden; }`);
  }
  // Resolve aliases once. An alias may intentionally name the asset itself.
  for (const [alias, target] of Object.entries(manifest.aliases)) {
    const vector = manifest.vectors[target];
    if (vector && !manifest.vectors[alias]) css.push(
      `html[data-ui-skin="${skin}"] svg.ui-icon.ui-icon--${alias} { background: url('/assets/ui/${skin}/${vector.file}') center / contain no-repeat; }`,
      `html[data-ui-skin="${skin}"] svg.ui-icon.ui-icon--${alias} > * { visibility: hidden; }`);
  }
  const h = assets['tutorial-hand'];
  variables.push(`--skin-hand-x: ${h.hotspot.x / h.frame.width};`, `--skin-hand-y: ${h.hotspot.y / h.frame.height};`);
  css.push(`html[data-ui-skin="${skin}"] { ${variables.join('\n')} }`);
  packs[skin] = { id: skin, name: manifest.name, base: `assets/ui/${skin}/`, aliases: manifest.aliases,
    palette: contract.styles[skin], assets, bundles, contractSha256: manifest.contractSha256 };
}
await fs.writeFile(path.join(root, 'js/uiStylePacks.generated.js'), '// Generated by scripts/generate-ui-style-packs.mjs.\nexport const UI_STYLE_PACKS = ' + JSON.stringify(packs, null, 2) + ';\n');
await fs.writeFile(path.join(root, 'styles/ui-style-packs.generated.css'), css.join('\n') + '\n');
console.log('Prepared two runtime packs: preferred WebP only and 66 SVG each; no atlases/source/QA.');
