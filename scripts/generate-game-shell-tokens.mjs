import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { GAME_SHELL_DEFAULTS, getGameShellCssVariables } from "../js/gameShell/gameShellConfig.js";

const directory = new URL("../styles/game-shell/", import.meta.url);
const target = new URL("tokens.css", directory);
const vars = Object.entries(getGameShellCssVariables()).map(([name, value]) => `  ${name}: ${value};`).join("\n");
// Media queries cannot consume custom properties: generate them from the same defaults.
const css = `/* Generated by scripts/generate-game-shell-tokens.mjs. Edit gameShellConfig.js. */
:root {
${vars}
}

.game-shell-tokens {
  --shell-safe-top: max(var(--shell-safe-area-top), env(safe-area-inset-top));
  --shell-safe-bottom: max(var(--shell-safe-area-bottom), env(safe-area-inset-bottom));
  --shell-active-board-gap: var(--shell-board-gap);
  --shell-active-board-padding: var(--shell-board-padding);
}

@media screen and (width <= ${GAME_SHELL_DEFAULTS.breakpoints.narrow}px) {
  .game-shell-tokens {
    --shell-active-board-gap: var(--shell-board-narrow-gap);
    --shell-active-board-padding: var(--shell-board-narrow-padding);
  }
}
`;

if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8").replaceAll("\r\n", "\n") !== css) {
    throw new Error("Game Shell tokens are stale. Run npm run shell:sync.");
  }
} else {
  mkdirSync(directory, { recursive: true });
  if (!existsSync(target) || readFileSync(target, "utf8").replaceAll("\r\n", "\n") !== css) writeFileSync(target, css);
  console.log(`Generated ${fileURLToPath(target)}.`);
}
