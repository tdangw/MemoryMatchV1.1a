import assert from 'node:assert/strict';
import { indexedDB } from 'fake-indexeddb';
globalThis.indexedDB=indexedDB;
const values=new Map();
globalThis.localStorage={getItem:key=>values.get(key)||null,setItem:(key,value)=>values.set(key,String(value)),removeItem:key=>values.delete(key)};
const persistence=await import('../js/persistence.js');
const journal=await import('../js/accountOperationJournal.js');
await persistence.loadPersistentGameData();
await persistence.ensureGameplaySeason();
await persistence.savePersistentGameData({coins:987});
await persistence.saveSyncMetadata('old-stats',{uid:'old-user',total:123});
journal.saveLocalAccountOperation({uid:'old-user',kind:'reset',space:'test-waves1'});
const oldWrite=persistence.updateSyncMetadata('old-stats',()=>({uid:'old-user',total:999}));
await persistence.clearAccountGameData();
await oldWrite;
assert.equal(await persistence.loadSyncMetadata('old-stats'),null);
assert.equal(await persistence.savePersistentGameData({coins:999}),false);
assert.equal(await persistence.saveSyncMetadata('old-stats',{uid:'old-user'}),false);
assert.equal(await persistence.updateSyncMetadata('old-stats',()=>({uid:'old-user'})),null);
assert.equal(await persistence.updateSyncMetadataPair(['old-stats','old-queue'],()=>[{},{}]),null);
localStorage.removeItem(journal.ACCOUNT_OPERATION_KEY); // Another tab acknowledges its fresh page.
assert.equal(await persistence.savePersistentGameData({coins:999}),false);
assert.equal(await persistence.updateSyncMetadata('old-stats',()=>({uid:'old-user'})),null);
journal.saveLocalAccountOperation({uid:'old-user',kind:'reset',space:'test-waves1',phase:'local-erasing'});
await persistence.saveAccountResetMetadata('test-waves1',{uid:'old-user',playerName:'Giữ tên',resetAt:123});
assert.equal((await persistence.loadSyncMetadata('test-waves1')).playerName,'Giữ tên');
assert.equal(await persistence.backfillAchievementInventory(),true);
journal.saveLocalAccountOperation({uid:'old-user',kind:'reset',space:'test-waves1',phase:'finished'});
assert.equal(await persistence.savePersistentGameData({coins:999}),false);
journal.acknowledgeFinishedAccountOperation();
assert.equal(journal.loadLocalAccountOperation(),null);
assert.equal((await persistence.loadPersistentGameData()).coins,0);
assert.equal(await persistence.loadSyncMetadata('old-stats'),null);
console.log('Local erasure blocks stale game, stats, paired metadata and outbox writes until fresh startup; reset identity survives.');
